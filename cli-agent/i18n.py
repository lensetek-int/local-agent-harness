def t(key: str, lang: str = "en", **kwargs) -> str:
    """Mengambil teks terjemahan berdasarkan key dan bahasa aktif."""
    lang_key = lang.lower().strip() if lang else "en"
    if lang_key in ("zh", "chinese"):
        lang_key = "cn"
    if lang_key not in MESSAGES:
        lang_key = "en"
    
    text = MESSAGES[lang_key].get(key)
    if text is None:
        text = MESSAGES["en"].get(key, key)
    
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text

