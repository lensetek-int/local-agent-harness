def _compute_investor_metrics(inv):
    # Bobot terkalibrasi realistis dari 6 dimensi Likert (skala 1-5)
    # Teknologi Edge (20%), Moat IP (20%), Market Urgency (20%), Monetisasi (20%), Risiko/Regulasi (10%), Tim Eksekusi (10%)
    raw_weighted = (
        inv["skor_teknologi_edge"] * 0.20
        + inv["skor_moat_ip"] * 0.20
        + inv["skor_kebutuhan_pasar"] * 0.20
        + inv["skor_kelayakan_monetisasi"] * 0.20
        + inv["skor_kesiapan_regulasi_risiko"] * 0.10
        + inv["skor_kualitas_tim_eksekusi"] * 0.10
    )
    conviction = round(((raw_weighted - 1.0) / 4.0) * 100.0 + inv.get("mandate_adj", 0.0), 1)
    conviction = max(12.0, min(96.0, conviction))
    inv["skor_konviksi_total"] = conviction

    # Penentuan probabilitas dan keputusan berdasarkan konviksi + kecocokan mandat
    mandate_pass = inv.get("force_pass", False)
    if mandate_pass or conviction < 56.0:
        inv["keputusan_investasi"] = "PASS"
        inv["probabilitas_investasi_pct"] = int(max(3, min(18, conviction * 0.3)))
    elif conviction >= 88.0:
        inv["keputusan_investasi"] = "STRONG YES"
        inv["probabilitas_investasi_pct"] = int(min(92, conviction - 2))
    elif conviction >= 70.0:
        inv["keputusan_investasi"] = "CONDITIONAL YES"
        inv["probabilitas_investasi_pct"] = int(max(45, min(72, conviction - 12)))
    else:
        inv["keputusan_investasi"] = "WAIT & SEE"
        inv["probabilitas_investasi_pct"] = int(max(20, min(42, conviction - 26)))
    return inv


